/**
 * Director persistence helpers — resilient reads/writes against the account-level
 * Director thread. Production databases may lag migrations (missing `reasoning`
 * column or artifact tables); these helpers degrade gracefully instead of 500ing.
 */
import { and, desc, eq, sql } from "drizzle-orm";
import { drizzle, log } from "./server-context";
import * as schema from "../db/schema";
import { getErrorMessage } from "./server-utils";
import { listDirectorArtifacts, type DirectorStoredArtifact } from "./director-artifacts";
import {
  completedStitchPreviewsForSession,
  mergeCompletedStitchPreviewMetadata,
  packDirectorMetadata,
  parseDirectorMetadata,
  stitchSessionMatches,
  type DirectorMessageMetadata,
  type DirectorPreviewMeta,
  type DirectorStitchSessionLookup,
  type DirectorStitchSessionMeta,
} from "./director-message-metadata";
import type { DirectorProposalResolution } from "./director-proposal-state";
import {
  DIRECTOR_THREAD_KEY,
  type DirectorConversationThreadKey,
  parseDirectorThreadKey,
} from "./director-thread-keys";

export interface DirectorStoredMessage {
  id: bigint;
  userId: string;
  role: string;
  content: string;
  reasoning: string | null;
  metadata: Record<string, unknown> | null;
  createdAt: Date;
}

export interface DirectorMessagesLoadResult {
  messages: DirectorStoredMessage[];
  degraded: boolean;
}

export interface DirectorArtifactsLoadResult {
  artifacts: DirectorStoredArtifact[];
  degraded: boolean;
}

let directorSchemaEnsured = false;

async function probeMessagesSchema(): Promise<boolean> {
  try {
    await drizzle.execute(
      sql`SELECT metadata, reasoning, thread_key FROM wireline_director_conversation_messages LIMIT 0`,
    );
    return true;
  } catch {
    return false;
  }
}

async function probeArtifactsSchema(): Promise<boolean> {
  try {
    await drizzle.execute(sql`SELECT 1 FROM wireline_director_artifacts LIMIT 0`);
    return true;
  } catch {
    return false;
  }
}

export function isPostgresMissingColumn(error: unknown, column = "reasoning"): boolean {
  const code = (error as { code?: string })?.code;
  if (code === "42703") return true;
  const msg = getErrorMessage(error).toLowerCase();
  return (
    msg.includes("42703") ||
    (msg.includes(column.toLowerCase()) &&
      (msg.includes("does not exist") || msg.includes("undefined_column")))
  );
}

export function isPostgresMissingRelation(error: unknown): boolean {
  const msg = getErrorMessage(error).toLowerCase();
  return msg.includes("42p01") || msg.includes("does not exist");
}

/** Best-effort DDL for Director tables/columns. Never blocks reads on failure. */
export async function ensureDirectorSchema(): Promise<void> {
  if (directorSchemaEnsured) return;

  const messagesReady = await probeMessagesSchema();
  const artifactsReady = await probeArtifactsSchema();
  if (messagesReady && artifactsReady) {
    directorSchemaEnsured = true;
    return;
  }

  const allowRuntimeDdl =
    process.env.DIRECTOR_ALLOW_RUNTIME_DDL === "1" || process.env.NODE_ENV !== "production";
  if (!allowRuntimeDdl) {
    log.warn("director schema incomplete; runtime DDL disabled in production", {
      messagesReady,
      artifactsReady,
    });
    return;
  }

  try {
    if (!messagesReady) {
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_director_conversation_messages (
          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id     UUID NOT NULL,
          role        TEXT NOT NULL CHECK (role IN ('Account Holder', 'director')),
          content     TEXT NOT NULL,
          created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_director_conv_user
          ON wireline_director_conversation_messages (user_id, created_at DESC);
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_director_conversation_messages
          ADD COLUMN IF NOT EXISTS reasoning TEXT;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_director_conversation_messages
          ADD COLUMN IF NOT EXISTS metadata JSONB DEFAULT '{}'::jsonb;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_director_conversation_messages
          ADD COLUMN IF NOT EXISTS thread_key TEXT NOT NULL DEFAULT 'director';
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_director_conv_user_thread
          ON wireline_director_conversation_messages (user_id, thread_key, created_at DESC);
      `);
    }

    if (!artifactsReady) {
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_director_artifact_objects (
          object_key  TEXT PRIMARY KEY,
          user_id     UUID NOT NULL,
          mime_type   TEXT NOT NULL,
          base64_data TEXT NOT NULL,
          size_bytes  INTEGER NOT NULL CHECK (size_bytes >= 0),
          created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_director_artifact_objects_user_created
          ON wireline_director_artifact_objects (user_id, created_at DESC);
      `);
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_director_artifacts (
          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id       UUID NOT NULL,
          thread_key    TEXT NOT NULL DEFAULT 'director',
          message_id    BIGINT,
          tool_name     TEXT NOT NULL,
          artifact_type TEXT NOT NULL,
          name          TEXT NOT NULL,
          object_key    TEXT NOT NULL REFERENCES wireline_director_artifact_objects(object_key) ON DELETE CASCADE,
          metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
          created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_director_artifacts_user_thread_created
          ON wireline_director_artifacts (user_id, thread_key, created_at DESC);
      `);
    }

    directorSchemaEnsured = true;
  } catch (e) {
    log.warn("ensureDirectorSchema DDL failed (will retry on next request)", {
      error: getErrorMessage(e),
    });
  }
}

export async function loadDirectorMessages(
  userId: string,
  limit: number,
  threadKey: DirectorConversationThreadKey = DIRECTOR_THREAD_KEY,
): Promise<DirectorMessagesLoadResult> {
  await ensureDirectorSchema();
  try {
    const messages = await drizzle
      .select({
        id: schema.directorConversationMessages.id,
        userId: schema.directorConversationMessages.userId,
        threadKey: schema.directorConversationMessages.threadKey,
        role: schema.directorConversationMessages.role,
        content: schema.directorConversationMessages.content,
        reasoning: schema.directorConversationMessages.reasoning,
        metadata: schema.directorConversationMessages.metadata,
        createdAt: schema.directorConversationMessages.createdAt,
      })
      .from(schema.directorConversationMessages)
      .where(
        and(
          eq(schema.directorConversationMessages.userId, userId),
          eq(schema.directorConversationMessages.threadKey, threadKey),
        ),
      )
      .orderBy(desc(schema.directorConversationMessages.createdAt))
      .limit(limit);
    return {
      messages: messages.map((m) => ({
        ...m,
        metadata: m.metadata as Record<string, unknown> | null,
      })),
      degraded: false,
    };
  } catch (e) {
    if (isPostgresMissingColumn(e, "thread_key")) {
      log.warn("director messages: thread_key column missing, falling back without filter", {
        userId,
      });
      try {
        const rows = await drizzle
          .select({
            id: schema.directorConversationMessages.id,
            userId: schema.directorConversationMessages.userId,
            role: schema.directorConversationMessages.role,
            content: schema.directorConversationMessages.content,
            reasoning: schema.directorConversationMessages.reasoning,
            metadata: schema.directorConversationMessages.metadata,
            createdAt: schema.directorConversationMessages.createdAt,
          })
          .from(schema.directorConversationMessages)
          .where(eq(schema.directorConversationMessages.userId, userId))
          .orderBy(desc(schema.directorConversationMessages.createdAt))
          .limit(limit);
        return {
          messages: rows.map((r) => ({
            ...r,
            metadata: r.metadata as Record<string, unknown> | null,
          })),
          degraded: true,
        };
      } catch (threadKeyFallbackError) {
        log.warn("director messages thread_key fallback failed", {
          userId,
          error: getErrorMessage(threadKeyFallbackError),
        });
      }
    }
    if (isPostgresMissingColumn(e)) {
      log.warn("director messages: column missing, falling back", { userId });
      try {
        const rows = await drizzle
          .select({
            id: schema.directorConversationMessages.id,
            userId: schema.directorConversationMessages.userId,
            role: schema.directorConversationMessages.role,
            content: schema.directorConversationMessages.content,
            createdAt: schema.directorConversationMessages.createdAt,
          })
          .from(schema.directorConversationMessages)
          .where(eq(schema.directorConversationMessages.userId, userId))
          .orderBy(desc(schema.directorConversationMessages.createdAt))
          .limit(limit);
        return {
          messages: rows.map((row) => ({ ...row, reasoning: null, metadata: null })),
          degraded: true,
        };
      } catch (fallbackError) {
        log.warn("director messages fallback failed", {
          userId,
          error: getErrorMessage(fallbackError),
        });
        return { messages: [], degraded: true };
      }
    }
    if (isPostgresMissingRelation(e)) {
      log.warn("director messages table missing, returning empty list", { userId });
      return { messages: [], degraded: true };
    }
    log.warn("director messages load failed, returning empty list", {
      userId,
      error: getErrorMessage(e),
    });
    return { messages: [], degraded: true };
  }
}

export async function insertDirectorMessage(input: {
  userId: string;
  role: "Account Holder" | "director";
  content: string;
  threadKey?: DirectorConversationThreadKey;
  reasoning?: string | null;
  metadata?: DirectorMessageMetadata | Record<string, unknown> | null;
}): Promise<void> {
  await ensureDirectorSchema();
  const metadataPayload =
    input.metadata && typeof input.metadata === "object" ? input.metadata : null;
  const threadKey = parseDirectorThreadKey(input.threadKey);
  const values = {
    userId: input.userId,
    threadKey,
    role: input.role,
    content: input.content,
    reasoning: input.reasoning ?? null,
    metadata: metadataPayload,
  };
  try {
    await drizzle.insert(schema.directorConversationMessages).values(values);
  } catch (e) {
    if (!isPostgresMissingColumn(e)) throw e;
    log.warn("director insert: column missing, falling back", { userId: input.userId });
    await drizzle.insert(schema.directorConversationMessages).values({
      userId: input.userId,
      role: input.role,
      content: input.content,
    });
  }
}

const RECENT_STITCH_MESSAGE_LIMIT = 40;

async function loadRecentDirectorStitchRows(userId: string): Promise<
  Array<{
    id: bigint;
    metadata: unknown;
  }>
> {
  await ensureDirectorSchema();
  return drizzle
    .select({
      id: schema.directorConversationMessages.id,
      metadata: schema.directorConversationMessages.metadata,
    })
    .from(schema.directorConversationMessages)
    .where(
      and(
        eq(schema.directorConversationMessages.userId, userId),
        eq(schema.directorConversationMessages.role, "director"),
      ),
    )
    .orderBy(
      desc(schema.directorConversationMessages.createdAt),
      desc(schema.directorConversationMessages.id),
    )
    .limit(RECENT_STITCH_MESSAGE_LIMIT);
}

export async function loadCompletedDirectorStitchPreview(
  input: { userId: string } & DirectorStitchSessionLookup,
): Promise<DirectorPreviewMeta[] | null> {
  try {
    const rows = await loadRecentDirectorStitchRows(input.userId);
    for (const row of rows) {
      const meta = parseDirectorMetadata(row.metadata);
      const previews = completedStitchPreviewsForSession(meta, input);
      if (previews) return previews;
    }
  } catch (e) {
    if (isPostgresMissingColumn(e, "metadata") || isPostgresMissingRelation(e)) {
      log.warn("director stitch preview lookup degraded", {
        userId: input.userId,
        error: getErrorMessage(e),
      });
      return null;
    }
    throw e;
  }
  return null;
}

export async function loadPendingDirectorStitchSession(
  input: { userId: string } & DirectorStitchSessionLookup,
): Promise<DirectorStitchSessionMeta | null> {
  try {
    const rows = await loadRecentDirectorStitchRows(input.userId);
    for (const row of rows) {
      const meta = parseDirectorMetadata(row.metadata);
      if (meta.stitchAssetsPending !== true) continue;
      if (!meta.stitchSession) continue;
      if (stitchSessionMatches(meta, input)) return meta.stitchSession;
    }
  } catch (e) {
    if (isPostgresMissingColumn(e, "metadata") || isPostgresMissingRelation(e)) {
      log.warn("director stitch pending session lookup degraded", {
        userId: input.userId,
        error: getErrorMessage(e),
      });
      return null;
    }
    throw e;
  }
  return null;
}

export async function persistDirectorStitchPreviewCompletion(
  input: { userId: string; previews: DirectorPreviewMeta[] } & DirectorStitchSessionLookup,
): Promise<boolean> {
  if (input.previews.length === 0) return false;
  try {
    const rows = await loadRecentDirectorStitchRows(input.userId);
    for (const row of rows) {
      const meta = parseDirectorMetadata(row.metadata);
      const next = mergeCompletedStitchPreviewMetadata(meta, input, input.previews);
      if (!next) continue;
      await drizzle
        .update(schema.directorConversationMessages)
        .set({ metadata: next })
        .where(
          and(
            eq(schema.directorConversationMessages.id, row.id),
            eq(schema.directorConversationMessages.userId, input.userId),
          ),
        );
      return true;
    }
  } catch (e) {
    if (isPostgresMissingColumn(e, "metadata") || isPostgresMissingRelation(e)) {
      log.warn("director stitch preview persist degraded", {
        userId: input.userId,
        error: getErrorMessage(e),
      });
      return false;
    }
    throw e;
  }
  return false;
}

export async function listDirectorArtifactsSafe(
  userId: string,
  limit = 100,
): Promise<DirectorArtifactsLoadResult> {
  await ensureDirectorSchema();
  try {
    const artifacts = await listDirectorArtifacts(userId, limit);
    return { artifacts, degraded: false };
  } catch (e) {
    if (isPostgresMissingRelation(e)) {
      log.warn("director artifacts tables missing, returning empty list", { userId });
      return { artifacts: [], degraded: true };
    }
    log.warn("director artifacts load failed, returning empty list", {
      userId,
      error: getErrorMessage(e),
    });
    return { artifacts: [], degraded: true };
  }
}

/** Persist proposal card resolution on a Director message (survives reload). */
export async function patchDirectorMessageResolved(
  userId: string,
  messageId: string,
  relativeKey: string,
  state: DirectorProposalResolution,
): Promise<boolean> {
  await ensureDirectorSchema();
  let id: bigint;
  try {
    id = BigInt(messageId);
  } catch {
    return false;
  }

  const rows = await drizzle
    .select({
      id: schema.directorConversationMessages.id,
      metadata: schema.directorConversationMessages.metadata,
    })
    .from(schema.directorConversationMessages)
    .where(
      and(
        eq(schema.directorConversationMessages.id, id),
        eq(schema.directorConversationMessages.userId, userId),
      ),
    )
    .limit(1);

  const row = rows[0];
  if (!row) return false;

  const meta = parseDirectorMetadata(row.metadata);
  const nextResolved: Record<string, DirectorProposalResolution> = {
    ...(meta.resolved ?? {}),
    [relativeKey]: state,
  };
  const nextMeta: DirectorMessageMetadata = { ...meta, resolved: nextResolved };
  const packed = packDirectorMetadata(nextMeta);

  await drizzle
    .update(schema.directorConversationMessages)
    .set({ metadata: packed })
    .where(
      and(
        eq(schema.directorConversationMessages.id, id),
        eq(schema.directorConversationMessages.userId, userId),
      ),
    );

  return true;
}

