/**
 * Wireline Design export packagers — Figma handoff ZIP, React component, design notes.
 */
import { loadDirectorArtifactData } from "./director-artifacts";
import { buildZipBuffer } from "./zip-buffer";
import type { DirectorPreviewMeta } from "./director-message-metadata";

export interface DesignExportArtifacts {
  html?: Buffer;
  image?: Buffer;
  htmlArtifactId?: string;
  imageArtifactId?: string;
}

export async function loadPreviewExportArtifacts(
  userId: string,
  preview: Pick<DirectorPreviewMeta, "htmlArtifactId" | "imageArtifactId">,
): Promise<DesignExportArtifacts> {
  const result: DesignExportArtifacts = {
    htmlArtifactId: preview.htmlArtifactId,
    imageArtifactId: preview.imageArtifactId,
  };

  if (preview.htmlArtifactId) {
    const loaded = await loadDirectorArtifactData({
      artifactId: preview.htmlArtifactId,
      userId,
    });
    if (loaded) result.html = loaded.data;
  }

  if (preview.imageArtifactId) {
    const loaded = await loadDirectorArtifactData({
      artifactId: preview.imageArtifactId,
      userId,
    });
    if (loaded) result.image = loaded.data;
  }

  if (!result.html && !result.image) {
    throw new Error("No exportable artifacts found for this preview.");
  }

  return result;
}

function extractColorsFromHtml(html: string): string[] {
  const colors = new Set<string>();
  const hex = html.match(/#[0-9a-fA-F]{3,8}\b/g) ?? [];
  for (const h of hex.slice(0, 24)) colors.add(h);
  const rgb = html.match(/rgba?\([^)]{3,40}\)/gi) ?? [];
  for (const r of rgb.slice(0, 12)) colors.add(r);
  return [...colors];
}

function extractFontsFromHtml(html: string): string[] {
  const fonts = new Set<string>();
  const matches = html.match(/font-family:\s*([^;}{]+)/gi) ?? [];
  for (const raw of matches.slice(0, 12)) {
    const family = raw
      .replace(/font-family:\s*/i, "")
      .trim()
      .replace(/[\'"]/g, "");
    if (family) fonts.add(family.split(",")[0]?.trim() ?? family);
  }
  return [...fonts];
}

export function buildDesignNotesMarkdown(input: {
  title: string;
  deviceType?: string;
  promptSummary?: string;
  html?: string;
}): string {
  const colors = input.html ? extractColorsFromHtml(input.html) : [];
  const fonts = input.html ? extractFontsFromHtml(input.html) : [];

  return [
    `# ${input.title}`,
    "",
    "## Preview",
    `- Device frame: ${input.deviceType || "responsive"}`,
    input.promptSummary ? `- Operator prompt: ${input.promptSummary}` : "",
    "",
    "## Visual signals (auto-extracted)",
    colors.length > 0 ? `- Colors: ${colors.join(", ")}` : "- Colors: (none detected)",
    fonts.length > 0 ? `- Typography: ${fonts.join(", ")}` : "- Typography: (none detected)",
    "",
    "## Handoff",
    "- `prototype.html` — live HTML/CSS prototype",
    "- `preview.png` — screenshot reference (when available)",
    "- `wireline-design.json` — structured metadata for Figma plugin (v2)",
    "",
    "Generated by Wireline Design.",
  ]
    .filter((line) => line !== "")
    .join("\n");
}

export function buildWirelineDesignJson(input: {
  title: string;
  deviceType?: string;
  renderId?: string;
  conceptId?: string;
  htmlArtifactId?: string;
  imageArtifactId?: string;
  html?: string;
}): Record<string, unknown> {
  return {
    version: 1,
    generator: "wireline-design",
    title: input.title,
    deviceType: input.deviceType ?? "DESKTOP",
    renderId: input.renderId,
    conceptId: input.conceptId,
    artifacts: {
      htmlArtifactId: input.htmlArtifactId,
      imageArtifactId: input.imageArtifactId,
    },
    tokens: {
      colors: input.html ? extractColorsFromHtml(input.html) : [],
      typography: input.html ? extractFontsFromHtml(input.html) : [],
    },
    exportedAt: new Date().toISOString(),
  };
}

export function buildFigmaExportZip(input: {
  title: string;
  deviceType?: string;
  renderId?: string;
  conceptId?: string;
  htmlArtifactId?: string;
  imageArtifactId?: string;
  html?: Buffer;
  image?: Buffer;
  promptSummary?: string;
}): Buffer {
  const htmlStr = input.html?.toString("utf8") ?? "";
  const notes = buildDesignNotesMarkdown({
    title: input.title,
    deviceType: input.deviceType,
    promptSummary: input.promptSummary,
    html: htmlStr,
  });
  const meta = buildWirelineDesignJson({
    title: input.title,
    deviceType: input.deviceType,
    renderId: input.renderId,
    conceptId: input.conceptId,
    htmlArtifactId: input.htmlArtifactId,
    imageArtifactId: input.imageArtifactId,
    html: htmlStr,
  });

  const files: Array<{ name: string; data: Buffer }> = [
    { name: "design-notes.md", data: Buffer.from(notes, "utf8") },
    { name: "wireline-design.json", data: Buffer.from(JSON.stringify(meta, null, 2), "utf8") },
  ];

  if (input.html) {
    files.push({ name: "prototype.html", data: input.html });
  }
  if (input.image) {
    files.push({ name: "preview.png", data: input.image });
  }

  return buildZipBuffer(files);
}

function escapeForTemplateLiteral(str: string): string {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function extractBodyInnerHtml(html: string): string {
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  return bodyMatch?.[1]?.trim() ?? html.trim();
}

export function htmlToReactTailwindComponent(
  html: string,
  componentName = "GeneratedDesign",
): string {
  const inner = extractBodyInnerHtml(html);
  const escaped = escapeForTemplateLiteral(inner);

  return `import React from "react";

/**
 * Wireline Design export — paste into your app and refine tokens/spacing.
 * Generated ${new Date().toISOString().slice(0, 10)}.
 */
export function ${componentName}() {
  return (
    <div
      className="wl-generated-design min-h-screen bg-paper text-ink"
      dangerouslySetInnerHTML={{ __html: \`${escaped}\` }}
    />
  );
}

export default ${componentName};
`;
}

export function buildReactExportZip(input: {
  title: string;
  html?: Buffer;
  image?: Buffer;
  promptSummary?: string;
}): Buffer {
  const htmlStr =
    input.html?.toString("utf8") ?? "<!doctype html><html><body><p>Empty</p></body></html>";
  const componentName =
    input.title.replace(/[^a-zA-Z0-9]/g, "").replace(/^[0-9]/, "D") || "GeneratedDesign";
  const tsx = htmlToReactTailwindComponent(htmlStr, componentName.slice(0, 48));
  const notes = buildDesignNotesMarkdown({
    title: input.title,
    promptSummary: input.promptSummary,
    html: htmlStr,
  });

  const files: Array<{ name: string; data: Buffer }> = [
    { name: `${componentName}.tsx`, data: Buffer.from(tsx, "utf8") },
    { name: "prototype.html", data: Buffer.from(htmlStr, "utf8") },
    { name: "design.md", data: Buffer.from(notes, "utf8") },
  ];

  if (input.image) {
    files.push({ name: "screenshot.png", data: input.image });
  }

  return buildZipBuffer(files);
}

