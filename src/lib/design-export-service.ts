export async function packageFigmaExportForUser(
  userId: string,
  preview: DirectorPreviewMeta & { promptSummary?: string },
): Promise<{ zip: Buffer; fileName: string }> {
  const artifacts = await loadPreviewExportArtifacts(userId, preview);
  const zip = buildFigmaExportZip({
    title: preview.title,
    deviceType: preview.deviceType,
    renderId: preview.renderId,
    conceptId: preview.conceptId,
    htmlArtifactId: artifacts.htmlArtifactId,
    imageArtifactId: artifacts.imageArtifactId,
    html: artifacts.html,
    image: artifacts.image,
    promptSummary: preview.promptSummary,
  });

  const slug = preview.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .slice(0, 32);

  return { zip, fileName: `wireline-figma-${slug || "export"}.zip` };
}

