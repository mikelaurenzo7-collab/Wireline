/**
 * Director routes — the account-level "manager" chat.
 *
 * One thread per operator (no agentId). The Director is always available —
 * it's the first thing a brand-new operator can talk to, before they own any
 * agents, and the strategist they return to once their fleet is running.
 *
 * Endpoints:
 *   GET    /api/director/messages  — load the thread (+ the operator's fleet).
 *   POST   /api/director/messages  — operator sends, Director replies.
 *   DELETE /api/director/messages  — clear the thread.
 *
 * Model strategy lives in lib/director-planner: Sonnet for normal turns,
 * Opus for explicit deep-analysis requests. Per-user rate limiting (shared
 * claudeRateLimiter) bounds cost on the POST path.
 */
import express, { type Response } from "express";
import { and, desc, eq, gte, sql } from "drizzle-orm";
import type { AuthenticatedRequest } from "../types/auth";
import { authenticateUser } from "../middleware/auth";
import { claudeRateLimiter } from "../middleware/api-rate-limits";
import { log, drizzle } from "../lib/server-context";
import * as schema from "../db/schema";
import { getErrorMessage } from "../lib/server-utils";
import { planDirector, type DirectorFleetAgent } from "../lib/director-planner";

const router = express.Router();

// Hard cap on stored history — keeps the LLM payload + storage bounded.
const MAX_THREAD_LENGTH = 200;
// How many messages we feed back to Claude as conversational context.
const CLAUDE_CONTEXT_WINDOW = 40;

// The Director table is created by /api/admin/migrate-director-workspace, but
// because the Director must ALWAYS be reachable (even on a fresh deploy where
// the migration hasn't been hit yet) we lazily ensure it exists once per
// process. CREATE TABLE IF NOT EXISTS is idempotent + cheap after the first.
let directorTableEnsured = false;
async function ensureDirectorTable(): Promise<void> {
  if (directorTableEnsured) return;
  await drizzle.execute(sql`
    CREATE TABLE IF NOT EXISTS wireline_director_conversation_messages (
      id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id     UUID NOT NULL,
      role        TEXT NOT NULL CHECK (role IN ('operator', 'director')),
      content     TEXT NOT NULL,
      created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);
  await drizzle.execute(sql`
    CREATE INDEX IF NOT EXISTS idx_director_conv_user
      ON wireline_director_conversation_messages (user_id, created_at DESC);
  `);
  directorTableEnsured = true;
}

async function loadFleet(userId: string): Promise<DirectorFleetAgent[]> {
  const rows = await drizzle
    .select({ id: schema.agents.id, name: schema.agents.name, role: schema.agents.role })
    .from(schema.agents)
    .where(eq(schema.agents.userId, userId))
    .orderBy(desc(schema.agents.createdAt));
  return rows.map((r) => ({ id: r.id, name: r.name ?? null, role: r.role ?? null }));
}

// GET /api/director/messages — load thread history + fleet snapshot.
router.get(
  "/api/director/messages",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    try {
      await ensureDirectorTable();
      const fleet = await loadFleet(req.user.id);
      const messages = await drizzle
        .select()
        .from(schema.directorConversationMessages)
        .where(eq(schema.directorConversationMessages.userId, req.user.id))
        .orderBy(desc(schema.directorConversationMessages.createdAt))
        .limit(MAX_THREAD_LENGTH);

      res.json({
        fleet,
        messages: messages.reverse().map((m) => ({
          id: String(m.id),
          role: m.role,
          content: m.content,
          createdAt: m.createdAt,
        })),
      });
    } catch (e) {
      log.error("director messages fetch failed", { error: getErrorMessage(e) });
      res.status(500).json({ error: "Failed to load Director messages" });
    }
  },
);

// POST /api/director/messages — operator sends, Director replies.
router.post(
  "/api/director/messages",
  authenticateUser,
  claudeRateLimiter,
  async (req: AuthenticatedRequest, res: Response) => {
    try {
      await ensureDirectorTable();
      const operatorMessage = String(req.body?.content || "").trim();
      if (!operatorMessage) {
        return res.status(400).json({ error: "Message content required" });
      }
      if (operatorMessage.length > 4000) {
        return res.status(400).json({ error: "Message too long — keep under 4000 chars" });
      }

      const fleet = await loadFleet(req.user.id);

      // Aggregate fleet activity (last 7 days) for context. Best-effort —
      // a failed stats query must never block the chat.
      let stats: { calls7d?: number; bookings7d?: number } | undefined;
      try {
        const since = new Date(Date.now() - 7 * 24 * 60 * 60 * 1000);
        const [[calls], [bookings]] = await Promise.all([
          drizzle
            .select({ n: sql<number>`count(*)::int` })
            .from(schema.callLogs)
            .where(
              and(eq(schema.callLogs.userId, req.user.id), gte(schema.callLogs.createdAt, since)),
            ),
          drizzle
            .select({ n: sql<number>`count(*)::int` })
            .from(schema.appointments)
            .where(
              and(
                eq(schema.appointments.userId, req.user.id),
                gte(schema.appointments.createdAt, since),
              ),
            ),
        ]);
        stats = { calls7d: calls?.n ?? 0, bookings7d: bookings?.n ?? 0 };
      } catch {
        stats = undefined;
      }

      // Thread history for LLM context (most recent first → reverse for order).
      const priorMessages = await drizzle
        .select()
        .from(schema.directorConversationMessages)
        .where(eq(schema.directorConversationMessages.userId, req.user.id))
        .orderBy(desc(schema.directorConversationMessages.createdAt))
        .limit(CLAUDE_CONTEXT_WINDOW);

      const history = priorMessages.reverse().map((m) => ({
        role: m.role === "operator" ? ("operator" as const) : ("director" as const),
        content: m.content,
      }));

      // Persist the operator's message immediately so it survives any LLM failure.
      await drizzle.insert(schema.directorConversationMessages).values({
        userId: req.user.id,
        role: "operator",
        content: operatorMessage,
      });

      let reply: string;
      let suggestions: unknown[] = [];
      let model: "sonnet" | "opus" = "sonnet";

      if (!process.env.ANTHROPIC_API_KEY) {
        reply =
          "I can't respond right now — the LLM isn't configured. Your message is saved; try again later.";
      } else {
        try {
          const plan = await planDirector({ operatorMessage, history, fleet, stats });
          reply = plan.reply;
          suggestions = plan.suggestions;
          model = plan.model;
        } catch (e) {
          log.error("director planner failed", { error: getErrorMessage(e) });
          reply =
            "Sorry — I'm having trouble responding right now. Your message is saved; try again in a moment.";
        }
      }

      await drizzle.insert(schema.directorConversationMessages).values({
        userId: req.user.id,
        role: "director",
        content: reply,
      });

      res.json({ reply, suggestions, model });
    } catch (e) {
      log.error("director POST failed", { error: getErrorMessage(e) });
      res.status(500).json({ error: "Failed to send message" });
    }
  },
);

// DELETE /api/director/messages — clear the thread for a fresh start.
router.delete(
  "/api/director/messages",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    try {
      await ensureDirectorTable();
      await drizzle
        .delete(schema.directorConversationMessages)
        .where(eq(schema.directorConversationMessages.userId, req.user.id));
      res.json({ cleared: true });
    } catch (e) {
      log.error("director clear failed", { error: getErrorMessage(e) });
      res.status(500).json({ error: "Failed to clear Director thread" });
    }
  },
);

export default router;
