/**
 * One-shot DDL migration endpoint for the SMS threads/messages tables.
 *
 * Why this exists: drizzle-kit push from this container can't reach
 * Supabase Postgres (the pooler port is firewalled and the direct DNS
 * doesn't resolve). The Vercel serverless function CAN reach Postgres,
 * so we expose a tiny auth-gated DDL endpoint that the platform owner
 * can curl after each deploy. All statements use IF NOT EXISTS so re-
 * running is idempotent and safe.
 *
 * Auth: requesting user's email must match OWNER_EMAIL env var. This is
 * NOT for self-serve schema changes — it's a deploy-time admin tool.
 */

import { Router, Request, Response } from "express";
import { drizzle, log } from "../lib/server-context";
import { sql } from "drizzle-orm";
import { authenticateUser } from "../middleware/auth";
import type { AuthenticatedRequest } from "../types/auth";

const router = Router();

router.post(
  "/api/admin/migrate-sms-tables",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    const ownerEmail = process.env.OWNER_EMAIL;
    if (!ownerEmail || req.user?.email !== ownerEmail) {
      return res.status(403).json({ error: "Owner only." });
    }

    try {
      // SMS threads — one per (user, customer_number) pair
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_sms_threads (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          agent_id text REFERENCES wireline_agents(id) ON DELETE SET NULL,
          customer_number text NOT NULL,
          status text DEFAULT 'open',
          summary text,
          unread_count integer DEFAULT 0 NOT NULL,
          last_message_at timestamptz DEFAULT now(),
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE UNIQUE INDEX IF NOT EXISTS idx_sms_threads_user_customer
        ON wireline_sms_threads (user_id, customer_number);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_threads_user_id
        ON wireline_sms_threads (user_id);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_threads_last_message
        ON wireline_sms_threads (last_message_at DESC);
      `);

      // SMS messages — append-only per thread
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_sms_messages (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id uuid NOT NULL,
          thread_id uuid REFERENCES wireline_sms_threads(id) ON DELETE CASCADE,
          direction text NOT NULL,
          body text NOT NULL,
          twilio_sid text,
          agent_id text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_messages_thread_created
        ON wireline_sms_messages (thread_id, created_at);
      `);

      // Agent teams — groups AI agents for call-center routing.
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_agent_teams (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          name text NOT NULL,
          sms_from_number text,
          manager_email text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_agent_teams_user_id
        ON wireline_agent_teams (user_id);
      `);
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_agent_team_members (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          team_id uuid REFERENCES wireline_agent_teams(id) ON DELETE CASCADE,
          agent_id text REFERENCES wireline_agents(id) ON DELETE CASCADE,
          role text DEFAULT 'member',
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE UNIQUE INDEX IF NOT EXISTS idx_agent_team_members_team_agent
        ON wireline_agent_team_members (team_id, agent_id);
      `);

      // Call queues — route inbound calls to least-busy agent in team.
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_call_queues (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          team_id uuid REFERENCES wireline_agent_teams(id) ON DELETE CASCADE,
          name text NOT NULL,
          vapi_number_id text,
          max_wait_seconds integer DEFAULT 60,
          overflow_action text DEFAULT 'voicemail',
          overflow_transfer_to text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_call_queues_user_id
        ON wireline_call_queues (user_id);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_call_queues_vapi_number
        ON wireline_call_queues (vapi_number_id);
      `);

      log.info("Master plan migration completed", { userId: req.user.id });
      return res.json({
        ok: true,
        message: "SMS + agent teams + call queues tables ensured.",
      });
    } catch (e: any) {
      log.error("SMS migration failed", { error: e?.message });
      return res.status(500).json({ error: e?.message || "Migration failed" });
    }
  },
);

/**
 * Auth-gated DDL endpoint for the password-reset tokens table +
 * the new agents.silence_timeout_seconds column. Idempotent: every
 * statement uses IF NOT EXISTS so re-running is safe.
 */
router.post(
  "/api/admin/migrate-auth-and-agent-extras",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    const ownerEmail = process.env.OWNER_EMAIL;
    if (!ownerEmail || req.user?.email !== ownerEmail) {
      return res.status(403).json({ error: "Owner only." });
    }

    try {
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_password_reset_tokens (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          token_hash text NOT NULL UNIQUE,
          expires_at timestamptz NOT NULL,
          used_at timestamptz,
          requested_ip text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id
        ON wireline_password_reset_tokens (user_id);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expires
        ON wireline_password_reset_tokens (expires_at);
      `);

      await drizzle.execute(sql`
        ALTER TABLE wireline_agents
        ADD COLUMN IF NOT EXISTS silence_timeout_seconds integer;
      `);

      log.info("Auth/agent extras migration completed", { userId: req.user.id });
      return res.json({
        ok: true,
        message: "wireline_password_reset_tokens + agents.silence_timeout_seconds ensured.",
      });
    } catch (e: any) {
      log.error("Auth/agent migration failed", { error: e?.message });
      return res.status(500).json({ error: e?.message || "Migration failed" });
    }
  },
);

/**
 * Auth-gated DDL endpoint for the post-launch competitive batch:
 *   - phone_numbers.campaign_label (attribution)
 *   - call_logs.outcome_tag + campaign_source
 *   - outbound_leads.pipeline_stage + campaign_source
 *   - cadences + cadence_runs (multi-touch outbound sequences)
 *   - supervisor_subscriptions (live barge-in / whisper)
 */
router.post(
  "/api/admin/migrate-competitive-batch",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    const ownerEmail = process.env.OWNER_EMAIL;
    if (!ownerEmail || req.user?.email !== ownerEmail) {
      return res.status(403).json({ error: "Owner only." });
    }

    try {
      await drizzle.execute(sql`
        ALTER TABLE wireline_phone_numbers
        ADD COLUMN IF NOT EXISTS campaign_label text;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_call_logs
        ADD COLUMN IF NOT EXISTS outcome_tag text;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_call_logs
        ADD COLUMN IF NOT EXISTS campaign_source text;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_outbound_leads
        ADD COLUMN IF NOT EXISTS pipeline_stage text DEFAULT 'cold';
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_outbound_leads
        ADD COLUMN IF NOT EXISTS campaign_source text;
      `);

      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_cadences (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          name text NOT NULL,
          description text,
          agent_id text,
          steps jsonb NOT NULL,
          active boolean DEFAULT true,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_cadences_user_id ON wireline_cadences (user_id);
      `);

      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_cadence_runs (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          cadence_id uuid NOT NULL,
          lead_id bigint NOT NULL,
          current_step integer DEFAULT 0 NOT NULL,
          next_due_at timestamptz,
          status text DEFAULT 'active',
          last_result text,
          created_at timestamptz DEFAULT now(),
          updated_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_cadence_runs_due
        ON wireline_cadence_runs (status, next_due_at)
        WHERE status = 'active';
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_cadence_runs_user_id
        ON wireline_cadence_runs (user_id);
      `);
      await drizzle.execute(sql`
        CREATE UNIQUE INDEX IF NOT EXISTS idx_cadence_runs_lead_unique
        ON wireline_cadence_runs (lead_id, cadence_id);
      `);

      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_supervisor_subscriptions (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id uuid NOT NULL,
          call_id text NOT NULL,
          mode text DEFAULT 'listen',
          note text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_supervisor_subs_call
        ON wireline_supervisor_subscriptions (call_id);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_supervisor_subs_user
        ON wireline_supervisor_subscriptions (user_id);
      `);

      log.info("Competitive batch migration completed", { userId: req.user.id });
      return res.json({
        ok: true,
        message:
          "phone_numbers.campaign_label + call_logs/outbound_leads attribution + cadences + cadence_runs + supervisor_subscriptions ensured.",
      });
    } catch (e: any) {
      log.error("Competitive batch migration failed", { error: e?.message });
      return res.status(500).json({ error: e?.message || "Migration failed" });
    }
  },
);

/**
 * Audit3 — adds `demo` boolean to four tables so the UI can pill-mark
 * seeded showcase rows. Idempotent. Backfills demo=true on rows whose
 * vapiCallId starts with 'seed-call-' (the seed script's signature) so
 * existing seeded data inherits the flag.
 */
router.post(
  "/api/admin/migrate-audit3",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    const ownerEmail = process.env.OWNER_EMAIL;
    if (!ownerEmail || req.user?.email !== ownerEmail) {
      return res.status(403).json({ error: "Owner only." });
    }
    try {
      await drizzle.execute(sql`
        ALTER TABLE wireline_call_logs
        ADD COLUMN IF NOT EXISTS demo boolean DEFAULT false NOT NULL;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_outbound_leads
        ADD COLUMN IF NOT EXISTS demo boolean DEFAULT false NOT NULL;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_appointments
        ADD COLUMN IF NOT EXISTS demo boolean DEFAULT false NOT NULL;
      `);
      await drizzle.execute(sql`
        ALTER TABLE wireline_dnc_list
        ADD COLUMN IF NOT EXISTS demo boolean DEFAULT false NOT NULL;
      `);

      // Backfill: mark prior seeded rows by their telltale signature.
      // - call_logs: vapi_call_id starts with 'seed-call-'
      // - outbound_leads: customer_number is one of the SAMPLE_CUSTOMERS
      //   phones (we use a narrow regex match to avoid false positives)
      // - appointments + dnc_list: phone in the same SAMPLE_CUSTOMERS set
      const seedPhones = sql`(
        '+14155551011','+12125551042','+16175552031','+13105551108','+12065552287',
        '+13125552233','+19173145555','+14025558810','+12063339090','+15103445454',
        '+17029990606','+19035552031'
      )`;
      const r1 = await drizzle.execute(sql`
        UPDATE wireline_call_logs SET demo = true
        WHERE demo = false AND vapi_call_id LIKE 'seed-call-%';
      `);
      const r2 = await drizzle.execute(sql`
        UPDATE wireline_outbound_leads SET demo = true
        WHERE demo = false AND customer_number IN ${seedPhones};
      `);
      const r3 = await drizzle.execute(sql`
        UPDATE wireline_appointments SET demo = true
        WHERE demo = false AND phone_number IN ${seedPhones};
      `);
      const r4 = await drizzle.execute(sql`
        UPDATE wireline_dnc_list SET demo = true
        WHERE demo = false AND phone IN ${seedPhones};
      `);

      log.info("Audit3 migration completed", {
        userId: req.user.id,
        backfilled: {
          call_logs: (r1 as any).rowCount ?? 0,
          outbound_leads: (r2 as any).rowCount ?? 0,
          appointments: (r3 as any).rowCount ?? 0,
          dnc_list: (r4 as any).rowCount ?? 0,
        },
      });
      return res.json({
        ok: true,
        message:
          "demo column added to call_logs / outbound_leads / appointments / dnc_list with backfill.",
      });
    } catch (e: any) {
      log.error("Audit3 migration failed", { error: e?.message });
      return res.status(500).json({ error: e?.message || "Migration failed" });
    }
  },
);

export default router;
