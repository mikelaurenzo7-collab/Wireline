/**
 * One-shot DDL migration endpoint for the SMS threads/messages tables.
 *
 * Why this exists: drizzle-kit push from this container can't reach
 * Supabase Postgres (the pooler port is firewalled and the direct DNS
 * doesn't resolve). The Vercel serverless function CAN reach Postgres,
 * so we expose a tiny auth-gated DDL endpoint that the platform owner
 * can curl after each deploy. All statements use IF NOT EXISTS so re-
 * running is idempotent and safe.
 *
 * Auth: requesting user's email must match OWNER_EMAIL env var. This is
 * NOT for self-serve schema changes — it's a deploy-time admin tool.
 */

import { Router, Request, Response } from "express";
import { drizzle, log } from "../lib/server-context";
import { sql } from "drizzle-orm";
import { authenticateUser } from "../middleware/auth";
import type { AuthenticatedRequest } from "../types/auth";

const router = Router();

router.post(
  "/api/admin/migrate-sms-tables",
  authenticateUser,
  async (req: AuthenticatedRequest, res: Response) => {
    const ownerEmail = process.env.OWNER_EMAIL;
    if (!ownerEmail || req.user?.email !== ownerEmail) {
      return res.status(403).json({ error: "Owner only." });
    }

    try {
      // SMS threads — one per (user, customer_number) pair
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_sms_threads (
          id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
          user_id uuid NOT NULL,
          agent_id text REFERENCES wireline_agents(id) ON DELETE SET NULL,
          customer_number text NOT NULL,
          status text DEFAULT 'open',
          summary text,
          unread_count integer DEFAULT 0 NOT NULL,
          last_message_at timestamptz DEFAULT now(),
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE UNIQUE INDEX IF NOT EXISTS idx_sms_threads_user_customer
        ON wireline_sms_threads (user_id, customer_number);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_threads_user_id
        ON wireline_sms_threads (user_id);
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_threads_last_message
        ON wireline_sms_threads (last_message_at DESC);
      `);

      // SMS messages — append-only per thread
      await drizzle.execute(sql`
        CREATE TABLE IF NOT EXISTS wireline_sms_messages (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id uuid NOT NULL,
          thread_id uuid REFERENCES wireline_sms_threads(id) ON DELETE CASCADE,
          direction text NOT NULL,
          body text NOT NULL,
          twilio_sid text,
          agent_id text,
          created_at timestamptz DEFAULT now()
        );
      `);
      await drizzle.execute(sql`
        CREATE INDEX IF NOT EXISTS idx_sms_messages_thread_created
        ON wireline_sms_messages (thread_id, created_at);
      `);

      log.info("SMS migration completed", { userId: req.user.id });
      return res.json({ ok: true, message: "SMS tables ensured." });
    } catch (e: any) {
      log.error("SMS migration failed", { error: e?.message });
      return res.status(500).json({ error: e?.message || "Migration failed" });
    }
  },
);

export default router;
