-- Director chat — the account-level strategist thread.
--
-- One thread per USER (no agent_id). The Director is always available, even
-- before the operator owns any agents, and acts as the "manager" that helps
-- plan, set up, and coach the fleet. Because it has no agent FK, its history
-- survives agent deletions. role is one of 'operator' | 'director'.
--
-- Idempotent — safe to re-run.

CREATE TABLE IF NOT EXISTS wireline_director_conversation_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID NOT NULL,
  role        TEXT NOT NULL CHECK (role IN ('operator', 'director')),
  content     TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_director_conv_user
  ON wireline_director_conversation_messages (user_id, created_at DESC);
