-- Director artifact object storage + metadata history.

CREATE TABLE IF NOT EXISTS wireline_director_artifact_objects (
  object_key  TEXT PRIMARY KEY,
  user_id     UUID NOT NULL,
  mime_type   TEXT NOT NULL,
  base64_data TEXT NOT NULL,
  size_bytes  INTEGER NOT NULL CHECK (size_bytes >= 0),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_director_artifact_objects_user_created
  ON wireline_director_artifact_objects (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS wireline_director_artifacts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       UUID NOT NULL,
  thread_key    TEXT NOT NULL DEFAULT 'director',
  message_id    BIGINT,
  tool_name     TEXT NOT NULL,
  artifact_type TEXT NOT NULL,
  name          TEXT NOT NULL,
  object_key    TEXT NOT NULL REFERENCES wireline_director_artifact_objects(object_key) ON DELETE CASCADE,
  metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_director_artifacts_user_thread_created
  ON wireline_director_artifacts (user_id, thread_key, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_director_artifacts_object
  ON wireline_director_artifacts (object_key);

ALTER TABLE wireline_director_artifact_objects ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON wireline_director_artifact_objects;
CREATE POLICY tenant_isolation ON wireline_director_artifact_objects
  FOR ALL
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid)
  WITH CHECK (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid);

ALTER TABLE wireline_director_artifacts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON wireline_director_artifacts;
CREATE POLICY tenant_isolation ON wireline_director_artifacts
  FOR ALL
  USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid)
  WITH CHECK (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid);
