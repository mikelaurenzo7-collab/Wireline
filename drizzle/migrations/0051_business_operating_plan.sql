-- Business operating plan: demo funnel + lesson approval status.

CREATE TABLE IF NOT EXISTS wireline_demo_call_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dialed_number text NOT NULL,
  showcase_agent text,
  caller_number_hash text,
  source text,
  intent_vertical text,
  recap_sent_at timestamptz,
  signup_user_id uuid,
  call_log_id bigint,
  vapi_call_id text,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_demo_call_events_created ON wireline_demo_call_events USING btree (created_at);
CREATE INDEX IF NOT EXISTS idx_demo_call_events_agent ON wireline_demo_call_events USING btree (showcase_agent) WHERE showcase_agent IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_demo_call_events_source ON wireline_demo_call_events USING btree (source) WHERE source IS NOT NULL;

ALTER TABLE wireline_agent_lessons
  ADD COLUMN IF NOT EXISTS lesson_status text DEFAULT 'approved';
