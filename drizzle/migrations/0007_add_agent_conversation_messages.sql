-- Migration: per-agent operator chat thread.
--
-- Each Wireline agent now has a private, persistent chat thread with
-- its operator — distinct from /train (configuration) and from
-- caller-facing call logs. Operators use this to coach the agent over
-- time, give ongoing direction, review last-week's calls together, and
-- attach files. The "workspace per agent" pattern Mike asked for.
--
-- One thread per (userId, agentId). Messages are append-only. Cascade
-- delete with the parent agent so deleting an agent removes its
-- workspace history (avoids dangling rows + GDPR-friendly).
--
-- Read pattern: most recent N messages by agent — covered by the
-- composite descending index on (user_id, agent_id, created_at).

CREATE TABLE IF NOT EXISTS wireline_agent_conversation_messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID NOT NULL,
  agent_id    TEXT NOT NULL REFERENCES wireline_agents(id) ON DELETE CASCADE,
  role        TEXT NOT NULL CHECK (role IN ('operator', 'agent')),
  content     TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_agent_conv_user_agent
  ON wireline_agent_conversation_messages (user_id, agent_id, created_at DESC);
