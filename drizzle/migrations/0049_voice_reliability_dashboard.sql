-- Voice reliability operating dashboard: per-call reliability columns + staging + webhook health.

ALTER TABLE wireline_call_logs
  ADD COLUMN IF NOT EXISTS ended_reason text,
  ADD COLUMN IF NOT EXISTS tool_calls_total integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS tool_calls_failed integer DEFAULT 0,
  ADD COLUMN IF NOT EXISTS escalation_attempted boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS escalation_succeeded boolean DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_call_logs_ended_reason ON wireline_call_logs USING btree (ended_reason) WHERE ended_reason IS NOT NULL;

CREATE TABLE IF NOT EXISTS wireline_call_reliability_staging (
  vapi_call_id text PRIMARY KEY,
  user_id uuid NOT NULL,
  tool_calls_total integer NOT NULL DEFAULT 0,
  tool_calls_failed integer NOT NULL DEFAULT 0,
  escalation_attempted boolean NOT NULL DEFAULT false,
  escalation_succeeded boolean NOT NULL DEFAULT false,
  updated_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_call_reliability_staging_user ON wireline_call_reliability_staging USING btree (user_id);

CREATE TABLE IF NOT EXISTS wireline_webhook_health (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  provider text NOT NULL,
  event_type text NOT NULL,
  outcome text NOT NULL,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_webhook_health_user_created ON wireline_webhook_health USING btree (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_webhook_health_provider_created ON wireline_webhook_health USING btree (provider, created_at);
