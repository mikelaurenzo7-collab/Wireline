import { readFileSync, statSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

const root = process.cwd();
const sourcePath = resolve(root, "public/wireline-stripe-logo.svg");
const pngPath = resolve(root, "public/wireline-stripe-logo.png");

function jpegDimensions(bytes: Buffer): { width: number; height: number } {
  expect(bytes.subarray(0, 2)).toEqual(Buffer.from([0xff, 0xd8]));
  let offset = 2;
  while (offset + 9 < bytes.length) {
    if (bytes[offset] !== 0xff) {
      offset += 1;
      continue;
    }
    const marker = bytes[offset + 1];
    if (marker === 0xd8 || marker === 0xd9) {
      offset += 2;
      continue;
    }
    const segmentLength = bytes.readUInt16BE(offset + 2);
    if ([0xc0, 0xc1, 0xc2].includes(marker)) {
      return {
        height: bytes.readUInt16BE(offset + 5),
        width: bytes.readUInt16BE(offset + 7),
      };
    }
    offset += 2 + segmentLength;
  }
  throw new Error("Stripe JPEG is missing a supported size header.");
}

describe("Stripe merchant-brand assets", () => {
  it("embeds the exact canonical mark and canonical design tokens", () => {
    const source = readFileSync(sourcePath, "utf8");
    const mark = readFileSync(resolve(root, "public/wireline-icon.svg"));
    const tokens = JSON.parse(
      readFileSync(resolve(root, "design-tokens/wireline.tokens.json"), "utf8"),
    );
    const embedded = source.match(/data:image\/svg\+xml;base64,([^"\s]+)/)?.[1];

    expect(embedded).toBeTruthy();
    expect(Buffer.from(embedded!, "base64")).toEqual(mark);
    expect(source).toContain(`fill="${tokens.color.action.primary.pressed.$value}"`);
    expect(source).toContain(`fill="${tokens.color.surface.default.$value}"`);
    expect(source).toContain(`font-family="${tokens.font.family.display.$value}, sans-serif"`);
    expect(source).toContain("Try Wireline");
  });

  it("is generated by the canonical image renderer", () => {
    const renderer = readFileSync(resolve(root, "scripts/render-image-assets.mjs"), "utf8");

    expect(renderer).toContain('readFileSync(resolve(root, "public/wireline-icon.svg")');
    expect(renderer).toContain('readFileSync(resolve(root, "design-tokens/wireline.tokens.json")');
    expect(renderer).toContain('out: "public/wireline-stripe-logo.png"');
  });

  it("renders a transparent, non-square Stripe-compatible PNG", () => {
    const png = readFileSync(pngPath);

    expect(png.subarray(0, 8)).toEqual(
      Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    );
    expect(png.readUInt32BE(16)).toBe(1200);
    expect(png.readUInt32BE(20)).toBe(360);
    expect([4, 6]).toContain(png.readUInt8(25));
    expect(statSync(pngPath).size).toBeLessThan(512_000);
  });

  it("ships conservative RGB JPEG fallbacks for Stripe dashboard uploads", () => {
    const icon = resolve(root, "public/wireline-stripe-icon.jpg");
    const logo = resolve(root, "public/wireline-stripe-logo.jpg");

    expect(jpegDimensions(readFileSync(icon))).toEqual({ width: 512, height: 512 });
    expect(jpegDimensions(readFileSync(logo))).toEqual({ width: 1200, height: 360 });
    expect(statSync(icon).size).toBeLessThan(512_000);
    expect(statSync(logo).size).toBeLessThan(512_000);
  });
});
